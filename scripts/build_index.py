#!/usr/bin/env python3
"""Validate the extensions, build their packages and write the repository index.

    python3 scripts/build_index.py                 validate, build dist/*.zip, write index.json and the README table
    python3 scripts/build_index.py --check         change nothing; fail if the committed outputs are stale
    python3 scripts/build_index.py --base-index F  also compare with the index F (the one on the base branch):
                                                   an extension whose package changed must have a higher versionCode

Standard library only. The rules mirror Manifest.problems(), ExtensionPackage and Catalog in Myspoti
(base/extensions/src/main/kotlin/app/myspoti/extensions), API version 1.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import struct
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXT_DIR = ROOT / "extensions"
DIST = ROOT / "dist"
INDEX = ROOT / "index.json"
BLOCKED = ROOT / "blocked.json"
README = ROOT / "README.md"

REPO_NAME = "Myspoti official extensions"
API_VERSION = 1
FORMAT = 1

# Package limits (Package.kt).
MAX_ZIP = 2 * 1024 * 1024
MAX_SCRIPT = 1024 * 1024
MAX_ICON = 256 * 1024
MAX_ICON_PX = 256
# Files a package may hold, in the order Package.pack() writes them (after manifest.json and main).
KEPT = ["manifest.json", "icon.png", "LICENSE", "LICENSE.txt", "README.md"]
ZIP_DATE = (1980, 1, 1, 0, 0, 0)

ID_RE = re.compile(r"[a-z][a-z0-9_]*(\.[a-z0-9_]+)+")
HOST_RE = re.compile(r"\*|(\*\.)?[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+")
KEY_RE = re.compile(r"[A-Za-z0-9_]{1,40}")
SHA_RE = re.compile(r"[0-9a-f]{64}")

# Hook / Permission -> sensitive? (Manifest.kt)
HOOKS = {"lyrics": False, "audio-source": True, "download-source": True}
PERMISSIONS = {
    "network": False,
    "player.read": True,
    "player.control": True,
    "notify": False,
    "spotify.catalog": False,
    "spotify.library.read": True,
    "spotify.write": True,
    "spotify.raw": True,
}
SETTING_TYPES = ["text", "secret", "toggle", "number", "choice"]

TABLE_START = "<!-- EXTENSIONS:START (generated by scripts/build_index.py, do not edit) -->"
TABLE_END = "<!-- EXTENSIONS:END -->"


class Failure(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def is_int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def asks(m: dict) -> list[dict]:
    """What the user is asked, as Manifest.asks(): the takeovers, then the rights."""
    out = []
    perms = m.get("permissions") or []
    for h in m.get("provides") or []:
        if h in HOOKS:
            why = next((p.get("why", "") for p in perms if p.get("name") == h), "")
            out.append({"key": h, "sensitive": HOOKS[h], "why": why})
    for p in perms:
        name = p.get("name")
        if name not in PERMISSIONS:
            continue
        if name == "network":
            anyhost = "*" in (p.get("hosts") or [])
            out.append({"key": "network.any" if anyhost else "network", "sensitive": anyhost, "why": p.get("why", "")})
        else:
            out.append({"key": name, "sensitive": PERMISSIONS[name], "why": p.get("why", "")})
    return out


def manifest_problems(m: dict) -> list[str]:
    """Manifest.problems(), plus the type checks Kotlin's decoder does."""
    p: list[str] = []

    def string(key, default=None):
        v = m.get(key, default)
        if not isinstance(v, str):
            p.append(f"{key}: a string is required" if default is None else f"{key}: must be a string")
            return default if default is not None else ""
        return v

    mid = string("id")
    name = string("name")
    version = string("version")
    author = string("author")
    description = string("description", "")
    main = string("main", "main.js")
    if "homepage" in m and m["homepage"] is not None and not isinstance(m["homepage"], str):
        p.append("homepage: must be a string")
    code = m.get("versionCode", 1)
    api = m.get("apiVersion", API_VERSION)
    if not is_int(code):
        p.append("versionCode: an integer")
        code = 1
    if not is_int(api):
        p.append("apiVersion: an integer")
        api = API_VERSION
    provides = m.get("provides", [])
    perms = m.get("permissions", [])
    settings = m.get("settings", [])
    if not isinstance(provides, list) or not all(isinstance(x, str) for x in provides):
        p.append("provides: a list of strings")
        provides = []
    if not isinstance(perms, list) or not all(isinstance(x, dict) for x in perms):
        p.append("permissions: a list of objects")
        perms = []
    if not isinstance(settings, list) or not all(isinstance(x, dict) for x in settings):
        p.append("settings: a list of objects")
        settings = []

    if not ID_RE.fullmatch(mid):
        p.append(f'id "{mid}": lower case, reverse-domain, at least two parts (io.github.you.name)')
    if not name.strip() or len(name) > 40:
        p.append("name: 1 to 40 characters")
    if not version.strip() or len(version) > 20:
        p.append("version: 1 to 20 characters")
    if code < 1:
        p.append("versionCode: 1 or more")
    if api < 1 or api > API_VERSION:
        p.append(f"apiVersion {api}: this repository is built for {API_VERSION}")
    if not author.strip() or len(author) > 60:
        p.append("author: 1 to 60 characters")
    if len(description) > 500:
        p.append("description: 500 characters at most")
    if not main.endswith(".js") or "/" in main or "\\" in main:
        p.append(f'main "{main}": a .js file at the root of the package')
    names = [x.get("name") for x in perms]
    if not provides and "player.read" not in names:
        p.append(f"provides: at least one of {', '.join(HOOKS)} (or player.read, for an extension that only listens)")
    for h in provides:
        if h not in HOOKS:
            p.append(f'provides "{h}": unknown (known: {", ".join(HOOKS)})')
    if len(provides) != len(set(provides)):
        p.append("provides: listed twice")
    for x in perms:
        pname = x.get("name")
        hosts = x.get("hosts", [])
        why = x.get("why", "")
        if not isinstance(pname, str):
            p.append("permission: a name is required")
            continue
        if not isinstance(hosts, list) or not all(isinstance(h, str) for h in hosts):
            p.append(f'permission "{pname}": hosts must be a list of strings')
            hosts = []
        if not isinstance(why, str):
            p.append(f'permission "{pname}": why must be a string')
        if pname not in PERMISSIONS and pname not in HOOKS:
            p.append(f'permission "{pname}": unknown (known: {", ".join(PERMISSIONS)})')
        elif pname in HOOKS and pname not in provides:
            p.append(f'permission "{pname}": a justification for a hook the extension does not provide')
        elif pname == "network" and not hosts:
            p.append('network: list the hosts it calls ("api.example.com", "*.example.com", or "*" for any)')
        elif pname == "network":
            for h in hosts:
                if not HOST_RE.fullmatch(h):
                    p.append(f'network host "{h}": a host name, *.domain, or *')
    if len(names) != len(set(names)):
        p.append("permissions: a name listed twice")
    for a in asks({"provides": provides, "permissions": [x for x in perms if isinstance(x.get("name"), str) and isinstance(x.get("why", ""), str)]}):
        if a["sensitive"] and len(a["why"].strip()) < 15:
            p.append(f'"{a["key"]}" is a sensitive right: say why the extension needs it in "why" (15 characters or more), the user reads it before installing')
    for s in settings:
        key = s.get("key", "")
        stype = s.get("type", "text")
        label = s.get("label", "")
        options = s.get("options", [])
        if not isinstance(key, str) or not KEY_RE.fullmatch(key):
            p.append(f'setting "{key}": letters, digits and _ only')
        if stype not in SETTING_TYPES:
            p.append(f'setting "{key}": type {stype} unknown ({", ".join(SETTING_TYPES)})')
        if stype == "choice" and not options:
            p.append(f'setting "{key}": a choice needs options')
        if not isinstance(label, str) or not label.strip():
            p.append(f'setting "{key}": a label')
    keys = [s.get("key") for s in settings]
    if len(keys) != len(set(keys)):
        p.append("settings: a key listed twice")
    return p


def png_size(data: bytes):
    if len(data) < 24 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", data[16:24])


def build_zip(folder: Path, manifest: dict) -> bytes:
    """The package, the same bytes for the same files (fixed order, dates and attributes)."""
    names = ["manifest.json", manifest.get("main", "main.js")]
    names += [n for n in KEPT if (folder / n).is_file() and n not in names]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for n in names:
            info = zipfile.ZipInfo(n, date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o644 << 16
            z.writestr(info, (folder / n).read_bytes(), compresslevel=9)
    return buf.getvalue()


class Ext:
    def __init__(self, folder: Path):
        self.folder = folder
        self.errors: list[str] = []
        self.manifest: dict = {}
        self.zip = b""
        self.sha = ""

    def fail(self, msg: str):
        self.errors.append(msg)

    def load(self):
        f = self.folder
        mpath = f / "manifest.json"
        if not mpath.is_file():
            return self.fail("manifest.json is missing")
        try:
            m = json.loads(mpath.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError) as e:
            return self.fail(f"manifest.json: {e}")
        if not isinstance(m, dict):
            return self.fail("manifest.json: an object is required")
        self.manifest = m
        for pr in manifest_problems(m):
            self.fail(f"manifest.json: {pr}")
        if self.errors:
            return
        if m["id"] != f.name:
            self.fail(f'folder "{f.name}" must be named after the extension id "{m["id"]}"')
        main = m.get("main", "main.js")
        script = f / main
        if not script.is_file():
            self.fail(f"{main} (main) is not in the extension folder")
        elif script.stat().st_size > MAX_SCRIPT:
            self.fail(f"{main} larger than 1 MB")
        allowed = set(KEPT) | {main}
        for child in sorted(f.iterdir()):
            if child.name not in allowed:
                self.fail(f"{child.name}: not part of an extension package (allowed: {', '.join(sorted(allowed))})")
        if not (f / "README.md").is_file():
            self.fail("README.md is required: what it does, what it reaches and why")
        if not ((f / "LICENSE").is_file() or (f / "LICENSE.txt").is_file()):
            self.fail("LICENSE is required: each extension declares its own license")
        icon = f / "icon.png"
        if icon.is_file():
            data = icon.read_bytes()
            size = png_size(data)
            if len(data) > MAX_ICON:
                self.fail("icon.png larger than 256 KB")
            if size is None:
                self.fail("icon.png: not a PNG")
            elif size[0] != size[1] or size[0] > MAX_ICON_PX:
                self.fail(f"icon.png is {size[0]}x{size[1]}: square, {MAX_ICON_PX} px or less")
        if self.errors:
            return
        self.zip = build_zip(f, m)
        if len(self.zip) > MAX_ZIP:
            self.fail("package larger than 2 MB")
        self.sha = sha256(self.zip)

    @property
    def zip_name(self) -> str:
        return f"{self.manifest['id']}-{self.manifest['version']}.zip"

    def entry(self) -> dict:
        """One entry of index.json, in Catalog.Entry's order, defaults left out like Catalog.encode()."""
        m = self.manifest
        e: dict = {"id": m["id"], "name": m["name"], "version": m["version"], "versionCode": m.get("versionCode", 1)}
        if m.get("apiVersion", API_VERSION) != API_VERSION:
            e["apiVersion"] = m["apiVersion"]
        e["author"] = m["author"]
        if m.get("description"):
            e["description"] = m["description"]
        if m.get("provides"):
            e["provides"] = list(m["provides"])
        if m.get("permissions"):
            perms = []
            for p in m["permissions"]:
                q = {"name": p["name"]}
                if p.get("hosts"):
                    q["hosts"] = list(p["hosts"])
                if p.get("why"):
                    q["why"] = p["why"]
                perms.append(q)
            e["permissions"] = perms
        e["url"] = f"dist/{self.zip_name}"
        e["sha256"] = self.sha
        e["size"] = len(self.zip)
        if (self.folder / "icon.png").is_file():
            e["icon"] = f"extensions/{m['id']}/icon.png"
        if m.get("homepage"):
            e["homepage"] = m["homepage"]
        return e


def read_blocked() -> list[dict]:
    if not BLOCKED.is_file():
        return []
    try:
        data = json.loads(BLOCKED.read_text(encoding="utf-8"))
    except ValueError as e:
        raise Failure(f"blocked.json: {e}")
    if not isinstance(data, list):
        raise Failure("blocked.json: a list is required")
    out = []
    for i, b in enumerate(data):
        where = f"blocked.json[{i}]"
        if not isinstance(b, dict) or not isinstance(b.get("id"), str) or not b["id"]:
            raise Failure(f"{where}: an object with an id")
        shas = b.get("sha256", [])
        if not isinstance(shas, list) or not all(isinstance(s, str) and SHA_RE.fullmatch(s) for s in shas):
            raise Failure(f"{where}: sha256 is a list of 64-digit hex hashes (empty: every version)")
        reason = b.get("reason", "")
        if not isinstance(reason, str) or not reason.strip():
            raise Failure(f"{where}: a reason is required (it is shown to the user)")
        e: dict = {"id": b["id"]}
        if shas:
            e["sha256"] = shas
        e["reason"] = reason
        out.append(e)
    return out


def render_index(entries: list[dict], blocked: list[dict]) -> str:
    doc: dict = {"format": FORMAT, "name": REPO_NAME}
    if entries:
        doc["extensions"] = entries
    if blocked:
        doc["blocked"] = blocked
    return json.dumps(doc, indent=4, ensure_ascii=False) + "\n"


def md(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def rights(e: dict) -> str:
    parts = []
    for a in asks({"provides": e.get("provides", []), "permissions": e.get("permissions", [])}):
        if a["key"] in HOOKS:
            continue
        parts.append(f"`{a['key']}`" + (" (sensitive)" if a["sensitive"] else ""))
    return ", ".join(parts) or "none"


def render_table(entries: list[dict]) -> str:
    if not entries:
        return "_No extension yet._"
    rows = ["| Extension | Version | Author | Provides | Rights asked | Description |", "|---|---|---|---|---|---|"]
    for e in entries:
        takes = ", ".join(f"`{h}`" + (" (sensitive)" if HOOKS.get(h) else "") for h in e.get("provides", [])) or "events only"
        link = f"[{md(e['name'])}](extensions/{e['id']}/)<br>`{e['id']}`"
        rows.append(f"| {link} | {md(e['version'])} | {md(e['author'])} | {takes} | {rights(e)} | {md(e.get('description', ''))} |")
    return "\n".join(rows)


def update_readme(text: str, table: str) -> str:
    start, end = text.find(TABLE_START), text.find(TABLE_END)
    if start < 0 or end < start:
        raise Failure(f"README.md: the markers {TABLE_START!r} and {TABLE_END!r} are missing")
    return text[: start + len(TABLE_START)] + "\n\n" + table + "\n\n" + text[end:]


def check_against_base(entries: list[dict], base_path: Path) -> list[str]:
    errors = []
    try:
        base = json.loads(base_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return errors  # no base index yet: everything is new
    old = {e["id"]: e for e in base.get("extensions", [])}
    for e in entries:
        o = old.get(e["id"])
        if not o:
            continue
        if e["versionCode"] < o["versionCode"]:
            errors.append(f'{e["id"]}: versionCode {e["versionCode"]} is lower than the published {o["versionCode"]}')
        elif e["sha256"] != o["sha256"] and e["versionCode"] == o["versionCode"]:
            errors.append(f'{e["id"]}: the package changed but versionCode is still {o["versionCode"]}: bump versionCode (and version)')
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="change nothing, fail if the committed outputs are stale")
    ap.add_argument("--base-index", type=Path, help="the index of the base branch: versionCode must go up when a package changes")
    args = ap.parse_args()

    folders = sorted(p for p in EXT_DIR.iterdir() if p.is_dir()) if EXT_DIR.is_dir() else []
    exts, problems = [], []
    for f in folders:
        x = Ext(f)
        x.load()
        exts.append(x)
        problems += [f"extensions/{f.name}: {e}" for e in x.errors]
    ids = [x.manifest.get("id") for x in exts if x.manifest]
    for i in set(ids):
        if ids.count(i) > 1:
            problems.append(f"id {i} is used twice")
    if problems:
        print("Validation failed:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1

    # The newest version of each extension (one folder per id: the folder is the current version).
    entries = sorted((x.entry() for x in exts), key=lambda e: (e["name"].lower(), e["id"]))
    try:
        blocked = read_blocked()
    except Failure as e:
        print(e, file=sys.stderr)
        return 1
    current_blocked = {b["id"] for b in blocked}
    for e in entries:
        if e["id"] in current_blocked:
            print(f'warning: {e["id"]} is in blocked.json and still has a folder: delete the folder', file=sys.stderr)

    if args.base_index:
        errs = check_against_base(entries, args.base_index)
        if errs:
            print("Version check failed:\n  " + "\n  ".join(errs), file=sys.stderr)
            return 1

    outputs: dict[Path, bytes] = {}
    for x in exts:
        outputs[DIST / x.zip_name] = x.zip
    outputs[INDEX] = render_index(entries, blocked).encode()
    try:
        outputs[README] = update_readme(README.read_text(encoding="utf-8"), render_table(entries)).encode()
    except Failure as e:
        print(e, file=sys.stderr)
        return 1

    stale = []
    for path, data in outputs.items():
        if not path.is_file() or path.read_bytes() != data:
            stale.append(path)
    # A published package never changes: a zip that already exists must be identical.
    immutable = [p for p in stale if p.parent == DIST and p.is_file()]
    if immutable:
        print("Published packages must not change; bump version and versionCode instead:\n  " + "\n  ".join(str(p.relative_to(ROOT)) for p in immutable), file=sys.stderr)
        return 1
    if args.check:
        if stale:
            print("Outputs are stale. Run `python3 scripts/build_index.py` and commit:\n  " + "\n  ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        print(f"ok: {len(exts)} extension(s), index.json and README.md are up to date")
        return 0

    DIST.mkdir(exist_ok=True)
    for path in stale:
        path.write_bytes(outputs[path])
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"ok: {len(exts)} extension(s)" + ("" if stale else ", nothing to change"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
